_TOOL_TEMPLATE = '''"""Tool: {description}

Generated by `agentbase add-extension tool --name {name}`.

Customize the tool function below, then add "{name}" to your agent's
tools list in configs/agents/default.yaml.

Usage in agent config::

    tools:
      - {name}
"""
from __future__ import annotations

from typing import Any

from langchain_core.tools import tool

from agentbase.extensions._meta import ExtensionMeta
from agentbase.registry.tools import register_tool

_META = ExtensionMeta(
    name="{name}",
    kind="tool",
    description="{description}",
    requires_context=[],  # Add context keys if needed (e.g. "workspace_dir")
    default_enabled=False,  # Set to True to enable by default
)


@register_tool("{name}", meta=_META)
def build_{name}_tool(context: dict[str, Any] | None = None):
    """Build the {name} tool instance.

    Args:
        context: Shared context dict from the agent factory.
            Available keys depend on agent config.

    Returns:
        A LangChain tool instance.
    """
    # Access context if needed
    # workspace = (context or {{}}).get("workspace_dir", ".")

    @tool
    def {name}(input_text: str) -> str:
        """{description}

        Args:
            input_text: Input text for the tool.

        Returns:
            The tool's output.
        """
        # TODO: Implement your tool logic here
        return f"{{input_text}} (processed by {name})"

    return {name}
'''

_TOOL_TEST_TEMPLATE = '''"""Tests for the {name} tool."""
from __future__ import annotations

import pytest

from agentbase.extensions.tools.{name} import build_{name}_tool


class Test{name_class}:
    def test_build_returns_tool(self):
        """Build function should return a callable tool."""
        t = build_{name}_tool(context={{}})
        assert t is not None
        assert callable(t)

    def test_tool_invocation(self):
        """Tool should process input and return a string."""
        t = build_{name}_tool(context={{}})
        result = t.invoke("hello")
        assert isinstance(result, str)
        assert len(result) > 0

    def test_tool_with_context(self):
        """Tool should accept context dict."""
        t = build_{name}_tool(context={{"workspace_dir": "/tmp"}})
        assert t is not None

    def test_tool_with_none_context(self):
        """Tool should handle None context."""
        t = build_{name}_tool(context=None)
        assert t is not None
'''


def generate_tool_scaffold(
    *,
    name: str,
    description: str = "",
    output_dir: Path = Path("."),
    force: bool = False,
    dry_run: bool = False,
) -> dict[str, str]:
    """Generate a tool extension scaffold.

    Creates two files:
    - ``extensions/tools/{name}.py`` — the tool implementation
    - ``tests/test_tool_{name}.py`` — the test template

    Args:
        name: Tool name (snake_case, e.g. ``"my_tool"``).
        description: Human-readable description.
        output_dir: Root directory for the project.
        force: Overwrite existing files.
        dry_run: Don't write files, just return what would be created.

    Returns:
        Dict mapping relative file paths to their content.
    """
    name = _validate_name(name)
    desc = description or f"Tool: {name}"
    name_class = _to_class_name(name)

    tool_content = _TOOL_TEMPLATE.format(name=name, description=desc)
    test_content = _TOOL_TEST_TEMPLATE.format(
        name=name, name_class=name_class, description=desc,
    )

    tool_path = output_dir / "extensions" / "tools" / f"{name}.py"
    test_path = output_dir / "tests" / f"test_tool_{name}.py"

    files = {
        str(tool_path): tool_content,
        str(test_path): test_content,
    }

    if not dry_run:
        for path_str, content in files.items():
            path = Path(path_str)
            if path.exists() and not force:
                logger.warning("File already exists: %s (use --force to overwrite)", path)
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            logger.info("Created: %s", path)

    return files


