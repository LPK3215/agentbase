"""Extension skeleton generator — generates tool/middleware/subagent scaffolds.

Generates standard extension files with:
- Proper imports and ExtensionMeta
- Registration decorator
- Build function pattern
- Test template with basic assertions
- Documentation stub

Usage::

    from agentbase.core.scaffold import generate_tool_scaffold

    generate_tool_scaffold(
        name="my_tool",
        description="Does something useful",
        output_dir=Path("."),
    )
    # → extensions/tools/my_tool.py
    # → tests/test_tool_my_tool.py
"""
from __future__ import annotations

import re
from pathlib import Path

from agentbase.runtime.logging import get_logger

logger = get_logger(__name__)


def _validate_name(name: str) -> str:
    """Validate that a name is a valid Python identifier (snake_case).

    Returns the validated name, or raises ValueError.
    """
    if not name:
        raise ValueError("Extension name cannot be empty")
    if not re.match(r"^[a-z][a-z0-9_]*$", name):
        raise ValueError(
            f"Invalid extension name '{name}': must be snake_case "
            "(lowercase, start with letter, only letters/digits/underscores)"
        )
    return name


def _to_class_name(snake_name: str) -> str:
    """Convert snake_case to PascalCase for class names."""
    return "".join(part.capitalize() for part in snake_name.split("_"))


